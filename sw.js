// Google Fonts only sends a font when a screen first uses it, so the fonts every theme needs are saved up front
// (Latin letters only; a failure here never stops the install).
const FONT_CSS=["https://fonts.googleapis.com/css2?family=Limelight&family=Inter:wght@400;500;600;700;800;900&family=Playfair+Display:wght@600;700&family=Fredoka:wght@600;700&display=swap", "https://fonts.googleapis.com/css2?family=Noto+Serif+SC:wght@700&text=%E4%B8%80%E4%BA%8C%E4%B8%89%E5%9B%9B%E4%BA%94%E5%85%AD%E4%B8%83%E5%85%AB%E4%B9%9D%E8%90%AC%E6%9D%B1%E5%8D%97%E8%A5%BF%E5%8C%97%E4%B8%AD%E7%99%BC&display=swap"];
async function saveFonts(c){
  for(const u of FONT_CSS){try{
    const res=await fetch(u);if(!res.ok)continue;const css=await res.clone().text();await c.put(u,res);
    const keep=[];css.replace(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*{[^}]*?url\(([^)]+)\)/g,(m,sub,f)=>{if(sub==='latin'||sub==='latin-ext')keep.push(f)});
    if(!/\/\*\s*[a-z-]+\s*\*\//.test(css))css.replace(/url\(([^)]+)\)/g,(m,f)=>{keep.push(f)});   // a single-file font (no subsets)
    await Promise.all(keep.map(f=>fetch(f,{mode:'cors'}).then(r=>r.ok?c.put(f,r):0).catch(()=>0)));
  }catch(err){}}
}
self.addEventListener('install',e=>{
  e.waitUntil(caches.open(CACHE).then(c=>c.addAll(FILES).then(()=>saveFonts(c))).then(()=>self.skipWaiting()));
});
self.addEventListener('activate',e=>{
  e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('amj-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));
});
const PAGE=new URL('index.html',self.registration.scope).href;
self.addEventListener('fetch',e=>{
  const r=e.request;if(r.method!=='GET')return;
  const u=new URL(r.url);
  const mine=u.origin===self.location.origin,font=u.hostname==='fonts.googleapis.com'||u.hostname==='fonts.gstatic.com';
  if(!mine&&!font)return;                       // multiplayer servers and anything else go straight to the network
  if(mine&&u.pathname.endsWith('/sw.js'))return;
  // pages and the game's own scripts come from the network first, so fixes reach players right away
  if(r.mode==='navigate'||(mine&&/\.(html|js|webmanifest)$|\/$/.test(u.pathname))){e.respondWith(pageFirst(r));return}
  e.respondWith(savedFirst(r));
});
// the game page: the network, unless it's offline or takes more than 4 seconds; then the saved copy
async function pageFirst(r){
  // each page is saved under its own address (without ?query), and the folder address is the game page
  let key=r.url.split(/[?#]/)[0];if(key===new URL('./',self.registration.scope).href)key=PAGE;
  const c=await caches.open(CACHE);const saved=()=>c.match(key);
  const net=fetch(r.url,{cache:'no-cache',credentials:'same-origin'}).then(res=>{if(res.ok)c.put(key,res.clone());return res});
  const slow=new Promise(ok=>setTimeout(ok,8000)).then(saved);
  try{const res=await Promise.race([net,slow]);if(res)return res;return await net}
  catch(err){const s=await saved();if(s)return s;throw err}
}
// everything else: the saved copy right away, refreshed in the background for next time
async function savedFirst(r){
  const c=await caches.open(CACHE);const hit=await c.match(r,{ignoreSearch:!r.url.includes('fonts.googleapis.com')});
  const net=fetch(r).then(res=>{if(res.ok||res.type==='opaque')c.put(r,res.clone());return res}).catch(()=>hit);
  return hit||net;
}
